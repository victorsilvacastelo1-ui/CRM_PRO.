-- Backfill an existing single-tenant installation into one organization.
do $$
declare
  v_organization_id bigint;
begin
  if exists (select 1 from public.sales) then
    insert into public.organizations(name)
    values ('CRM Pro')
    returning id into v_organization_id;

    update public.sales set organization_id = v_organization_id
      where organization_id is null;
    update public.companies set organization_id = v_organization_id
      where organization_id is null;
    update public.contacts set organization_id = v_organization_id
      where organization_id is null;
    update public.contact_notes set organization_id = v_organization_id
      where organization_id is null;
    update public.deals set organization_id = v_organization_id
      where organization_id is null;
    update public.deal_notes set organization_id = v_organization_id
      where organization_id is null;
    update public.tags set organization_id = v_organization_id
      where organization_id is null;
    update public.tasks set organization_id = v_organization_id
      where organization_id is null;
    update public.configuration set organization_id = v_organization_id
      where organization_id is null;

    insert into public.organization_members(organization_id, user_id, role)
    select
      v_organization_id,
      s.user_id,
      case when s.administrator then 'admin' else 'member' end
    from public.sales s
    on conflict (user_id) do nothing;
  else
    -- The legacy configuration row is global. In a fresh SaaS install,
    -- per-organization configuration is created when the first user signs up.
    delete from public.configuration where organization_id is null;
  end if;
end
$$;

