create or replace function public.current_organization_id()
returns bigint
language sql
stable
security definer
set search_path = ''
as $$
  select om.organization_id
  from public.organization_members om
  where om.user_id = auth.uid()
  limit 1
$$;

create or replace function public.is_org_member(target_organization_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.organization_members om
    where om.user_id = auth.uid()
      and om.organization_id = target_organization_id
  )
$$;

create or replace function public.is_org_admin(target_organization_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.sales s
    where s.user_id = auth.uid()
      and s.organization_id = target_organization_id
      and s.administrator = true
      and s.disabled = false
  )
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.is_org_admin(public.current_organization_id())
$$;

-- Set both the salesperson and organization on new customer-owned records.
create or replace function public.set_sales_id_default()
returns trigger
language plpgsql
set search_path = 'public'
as $$
declare
  v_organization_id bigint;
begin
  v_organization_id := public.current_organization_id();

  if v_organization_id is null then
    raise exception 'Authenticated user is not associated with an organization';
  end if;

  if new.organization_id is null then
    new.organization_id := v_organization_id;
  elsif new.organization_id <> v_organization_id then
    raise exception 'Cross-organization insert is not allowed';
  end if;

  if new.sales_id is null then
    select id into new.sales_id
    from public.sales
    where user_id = auth.uid()
      and organization_id = v_organization_id;
  end if;

  return new;
end
$$;

create or replace function public.set_organization_id_default()
returns trigger
language plpgsql
set search_path = 'public'
as $$
declare
  v_organization_id bigint;
begin
  v_organization_id := public.current_organization_id();

  if v_organization_id is null then
