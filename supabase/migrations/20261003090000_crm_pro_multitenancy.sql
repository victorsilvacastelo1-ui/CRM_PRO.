-- CRM Pro multi-tenant foundation
-- This migration converts the original single-installation CRM schema into
-- an organization-scoped SaaS model.
--
-- IMPORTANT: review and test on a non-production Supabase project before
-- applying to any live customer database.

begin;

-- ---------------------------------------------------------------------------
-- Organizations and memberships
-- ---------------------------------------------------------------------------

create table if not exists public.organizations (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id bigint not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member'
    check (role in ('owner', 'admin', 'member')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id),
  constraint organization_members_one_org_per_user unique (user_id)
);

