-- New public signups create a new organization.
-- Invited users can only join an existing organization when organization_id is
-- placed in raw_app_meta_data by an admin/service-role call.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_organization_id bigint;
  v_role text;
  v_org_name text;
begin
  v_organization_id := nullif(new.raw_app_meta_data ->> 'organization_id', '')::bigint;

  if v_organization_id is not null then
    if not exists (
      select 1 from public.organizations o where o.id = v_organization_id
    ) then
      raise exception 'Invited organization does not exist';
    end if;

    v_role := case
      when new.raw_app_meta_data ->> 'organization_role' in ('admin', 'member')
        then new.raw_app_meta_data ->> 'organization_role'
      else 'member'
    end;
  else
    v_org_name := coalesce(
      nullif(new.raw_user_meta_data ->> 'organization_name', ''),
      nullif(trim(concat(
        coalesce(new.raw_user_meta_data ->> 'first_name', ''),
        ' ',
        coalesce(new.raw_user_meta_data ->> 'last_name', '')
      )), ''),
      'Minha empresa'
    );

    insert into public.organizations(name)
    values (v_org_name)
    returning id into v_organization_id;

    v_role := 'owner';
  end if;

  insert into public.organization_members(organization_id, user_id, role)
  values (v_organization_id, new.id, v_role);

  insert into public.sales(
    first_name,
    last_name,
    email,
    user_id,
    administrator,
    organization_id
  )
  values (
    coalesce(
      new.raw_user_meta_data ->> 'first_name',
      new.raw_user_meta_data -> 'custom_claims' ->> 'first_name',
      'Pending'
    ),
    coalesce(
      new.raw_user_meta_data ->> 'last_name',
      new.raw_user_meta_data -> 'custom_claims' ->> 'last_name',
      'Pending'
    ),
    new.email,
    new.id,
    v_role in ('owner', 'admin'),
    v_organization_id
  );

  insert into public.configuration(organization_id, id, config)
  values (v_organization_id, 1, '{}'::jsonb)
  on conflict (organization_id, id) do nothing;

  return new;
end
$$;

