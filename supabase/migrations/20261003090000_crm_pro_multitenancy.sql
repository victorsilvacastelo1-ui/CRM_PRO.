do $$
declare
  p record;
begin
  for p in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = any(array[
        'organizations',
        'organization_members',
        'companies',
        'contacts',
        'contact_notes',
        'deals',
        'deal_notes',
        'sales',
        'tags',
        'tasks',
        'configuration',
        'favicons_excluded_domains'
      ])
  loop
    execute format(
      'drop policy if exists %I on %I.%I',
      p.policyname,
      p.schemaname,
      p.tablename
    );
  end loop;
end
$$;

